def test_maruto_hooks_10_vs_2x10():
    # Спорт: пара 68719590199 vs 63912, предсказано 0.98, золото 0
    qa, fa = _q("maruto / крючки универсальные maruto 3263, цвет br, № 7, 10 шт.",
                '{"страна производства":"россия","вес товара с упаковкой (г)":"2 г","валюта":"rub"}')
    qb, fb = _q("maruto, крючки универсальные maruto 3263, цвет br, № 7, 2 набора по 10 штук",
                '{"бренд":"maruto","страна-изготовитель":"россия","вид крючка":"одинарный",'
                '"размер крючка, n":"7","количество упаковок, шт":"10","тип":"крючок рыболовный"}')
    assert (qa, fa) == (10, True)
    assert (qb, fb) == (20, True)
    ft = _f("maruto / крючки универсальные maruto 3263, цвет br, № 7, 10 шт.", None,
            "maruto, крючки универсальные maruto 3263, цвет br, № 7, 2 набора по 10 штук", None)
    assert ft[7] == 1.0 and ft[6] == 1.0 and ft[5] == 2.0  # conflict, кратность, ratio=2


