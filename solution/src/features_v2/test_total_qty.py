# ---- синтетика по формулировкам из ТЗ ----

def test_spec_phrases():
    assert _q("упаковка 100 шт")[0] == 100
    assert _q("носки, 5 пар")[0] == 5
    assert _q("комплект из 3") == (3, True)
    assert _q("2 набора по 10 штук") == (20, True)
    assert _q("товар без количества") == (1, False)
    assert _q(None, None) == (1, False)
    assert _q("товар", "не json") == (1, False)


def test_feature_vector_shape_and_values():
    ft = _f("крючки, 10 шт.", None, "крючки, 2 набора по 10 штук", None)
    assert len(ft) == 8
    assert ft == (10.0, 20.0, 1.0, 1.0, 0.0, 2.0, 1.0, 1.0)
    ft_eq = _f("ручка, 1 шт", None, "ручка", None)
    assert ft_eq[4] == 1.0 and ft_eq[7] == 0.0 and ft_eq[2] == 1.0 and ft_eq[3] == 0.0
    # некратный конфликт
    ft_nc = _f("зажимы 12 шт", None, "зажимы 5 шт", None)
    assert ft_nc[6] == 0.0 and ft_nc[7] == 1.0
    # кап ratio
    ft_cap = _f("скрепки 1000 шт", None, "скрепки 10 шт", None)
    assert ft_cap[5] == 10.0


